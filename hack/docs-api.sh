set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mode="${1:-generate}"
if [[ "$mode" != generate && "$mode" != check ]]; then
  echo 'Usage: hack/docs-api.sh [generate|check]' >&2
  exit 2
fi
scratch="$(mktemp -d)"
trap 'rm -rf "$scratch"' EXIT
reference="$root/docs/content/docs/reference/api.md"

# Keep the generator's dependencies out of the controller module. Go caches the
# pinned tool; no downloaded executable or Python environment is maintained here.
go -C "$root/hack/tools" tool crd-ref-docs \
  --source-path="$root/api" \
  --config="$root/docs/api-reference.yaml" \
  --renderer=markdown --output-path="$scratch/reference.md"
{
  cat <<'FRONTMATTER'
---
title: API reference
weight: 10
description: Generated reference for the ChangeWindow Kubernetes API.
---

<!-- Generated by task docs:generate from api/v1alpha1. Do not edit. -->

FRONTMATTER
  # Make API types directly navigable in the page table of contents.
  sed '/^# API Reference$/d; s/^#### /## /; s/[[:blank:]]*$//' "$scratch/reference.md" |
    awk 'NF { if (blank && seen) print ""; print; blank=0; seen=1; next } { blank=1 }'
} > "$scratch/page.md"
if [[ "$mode" == check ]]; then
  diff -u "$reference" "$scratch/page.md" || {
    echo 'API reference is stale. Run task docs:generate.' >&2
    exit 1
  }
else
  cp "$scratch/page.md" "$reference"
fi
